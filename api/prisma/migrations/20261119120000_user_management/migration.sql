CREATE TYPE "UserStatus" AS ENUM ('ACTIVE', 'SUSPENDED');

CREATE TYPE "UserPermission" AS ENUM (
    'INCIDENTS_READ',
    'INCIDENTS_CREATE',
    'INCIDENTS_UPDATE',
    'INCIDENTS_DELETE',
    'USERS_MANAGE',
    'SETTINGS_MANAGE'
);

ALTER TABLE "User"
ADD COLUMN "status" "UserStatus" NOT NULL DEFAULT 'ACTIVE',
ADD COLUMN "permissions" "UserPermission"[] NOT NULL
DEFAULT ARRAY['INCIDENTS_READ', 'INCIDENTS_UPDATE']::"UserPermission"[];
